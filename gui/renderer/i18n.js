  var LANGUAGES = ["en", "zh"];
  var current = "en";
  var listeners = [];

  function normalize(lang) {
    var value = String(lang || "").toLowerCase();
    return value.indexOf("zh") === 0 ? "zh" : "en";
  }

  function detect(storage) {
    try {
      var saved = storage && storage.getItem("yakusha.lang");
      if (saved === "en" || saved === "zh") return saved;
    } catch (error) { /* storage is optional */ }
    try {
      if (typeof navigator !== "undefined") {
        var language = navigator.language || (navigator.languages && navigator.languages[0]) || "";
        return normalize(language);
      }
    } catch (error) { /* navigator is optional in tests */ }
    return "en";
  }

  function format(text, params) {
    if (!params) return text;
    return String(text).replace(/\{(\w+)\}/g, function (match, name) {
      return Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match;
    });
  }

  function t(key, params) {
    var table = STRINGS[current] || STRINGS.en;
    var value = Object.prototype.hasOwnProperty.call(table, key) ? table[key] : null;
    if (value === null) value = Object.prototype.hasOwnProperty.call(STRINGS.en, key) ? STRINGS.en[key] : null;
    if (value === null) return String(key);
    return format(value, params);
  }

  function apply(root) {
    if (!root || typeof root.querySelectorAll !== "function") return;
    var groups = [
      ["[data-i18n]", "text"],
      ["[data-i18n-title]", "title"],
      ["[data-i18n-aria-label]", "aria-label"],
      ["[data-i18n-placeholder]", "placeholder"],
    ];
    for (var i = 0; i < groups.length; i += 1) {
      var selector = groups[i][0];
      var kind = groups[i][1];
      var nodes;
      try { nodes = root.querySelectorAll(selector); } catch (error) { nodes = []; }
      for (var j = 0; j < nodes.length; j += 1) {
        var node = nodes[j];
        if (!node) continue;
        var key = kind === "text" ? node.dataset && node.dataset.i18n
          : kind === "title" ? node.dataset && node.dataset.i18nTitle
          : kind === "aria-label" ? node.dataset && node.dataset.i18nAriaLabel
          : node.dataset && node.dataset.i18nPlaceholder;
        if (!key) continue;
        var value = t(key);
        if (kind === "text") node.textContent = value;
        else if (kind === "title") node.title = value;
        else if (kind === "aria-label") { if (typeof node.setAttribute === "function") node.setAttribute("aria-label", value); }
        else node.placeholder = value;
      }
    }
  }

  function setLanguage(lang) {
    current = normalize(lang);
    for (var i = 0; i < listeners.length; i += 1) listeners[i](current);
    return current;
  }

  function onChange(fn) {
    if (typeof fn === "function") listeners.push(fn);
  }

  return Object.freeze({
    STRINGS: STRINGS,
    LANGUAGES: LANGUAGES,
    normalize: normalize,
    detect: detect,
    t: t,
    apply: apply,
    setLanguage: setLanguage,
    getLanguage: function () { return current; },
    onChange: onChange,
  });
