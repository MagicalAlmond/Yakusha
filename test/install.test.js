import { test } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { openProject } from "../src/core/mzproject.js";
import { readPluginsFile, parsePluginsJs } from "../src/core/pluginsfile.js";
import { buildRules } from "../src/core/fields.js";
import {
  installPlugin,
  uninstallPlugin,
  isInstalled,
  renderPlugin,
  PLUGIN_NAME,
  PLUGIN_FILE,
} from "../src/core/install.js";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const FIXTURE = path.join(HERE, "fixtures", "mini-mz");

/** Copy the fixture so the repository copy is never mutated by a test. */
function sandbox() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "yakusha-"));
  fs.cpSync(FIXTURE, path.join(dir, "game"), { recursive: true });
  return path.join(dir, "game");
}

test("renderPlugin embeds the current rules", () => {
  const source = renderPlugin();
  assert.ok(source.includes("const RULES = "));
  assert.ok(source.includes("const EMBEDDED = null;"));
  const match = source.match(/const RULES = (\{.*?\});\n/);
  assert.ok(match, "rules literal not found");
  assert.deepEqual(JSON.parse(match[1]), buildRules());
});

test("renderPlugin can embed a dictionary", () => {
  const source = renderPlugin({ embed: { a: "b" } });
  assert.ok(source.includes('const EMBEDDED = {"a":"b"};'));
});

test("install writes the plugin and registers it", () => {
  const root = sandbox();
  const project = openProject(root);
  assert.equal(isInstalled(project).installed, false);

  const result = installPlugin(project);
  assert.equal(result.state, "added");
  assert.equal(result.registered, true);
  assert.equal(result.createdBackup, true);

  const pluginPath = path.join(project.pluginDir, PLUGIN_FILE);
  assert.ok(fs.existsSync(pluginPath));
  const plugins = readPluginsFile(project.pluginsFile);
  const entry = plugins.find((p) => p.name === PLUGIN_NAME);
  assert.ok(entry, "plugin not registered");
  assert.equal(entry.status, true);
  assert.equal(entry.parameters.dictionaryPath, "yakusha/dictionary.json");
  assert.equal(entry.parameters.strictCodes, "true");

  assert.deepEqual(isInstalled(project), { installed: true, registered: true, pluginPath });
});

test("install is idempotent", () => {
  const root = sandbox();
  const project = openProject(root);
  installPlugin(project);
  const first = readPluginsFile(project.pluginsFile);
  const second = installPlugin(project);
  assert.equal(second.state, "unchanged");
  assert.equal(second.createdBackup, false);
  assert.deepEqual(readPluginsFile(project.pluginsFile), first);
});

test("uninstall restores plugins.js byte for byte", () => {
  const root = sandbox();
  const project = openProject(root);
  const before = fs.readFileSync(project.pluginsFile, "utf8");

  installPlugin(project);
  assert.notEqual(fs.readFileSync(project.pluginsFile, "utf8"), before);

  const result = uninstallPlugin(project);
  assert.equal(result.removed, true);
  assert.equal(result.restored, true);
  assert.equal(fs.readFileSync(project.pluginsFile, "utf8"), before);
  assert.equal(fs.existsSync(path.join(project.pluginDir, PLUGIN_FILE)), false);
  assert.equal(fs.existsSync(project.pluginsFile + ".yakusha-backup"), false);
});

test("uninstall on a clean game is a no-op", () => {
  const root = sandbox();
  const project = openProject(root);
  const before = fs.readFileSync(project.pluginsFile, "utf8");
  const result = uninstallPlugin(project);
  assert.equal(result.removed, false);
  assert.equal(result.restored, false);
  assert.equal(fs.readFileSync(project.pluginsFile, "utf8"), before);
});

test("plugins.js keeps the RPG Maker layout", () => {
  const root = sandbox();
  const project = openProject(root);
  installPlugin(project);
  const text = fs.readFileSync(project.pluginsFile, "utf8");
  assert.ok(text.startsWith("// Generated by RPG Maker.\n// Do not edit this file directly.\nvar $plugins =\n[\n"));
  // The fixture deliberately ends with a plain "\n];" (no trailing comma).
  // Rewriting it the way RPG Maker would is still valid JS, but it turns a one
  // entry edit into a whole file diff, so the original shape is preserved.
  assert.ok(text.endsWith("\n];\n"));
  assert.ok(parsePluginsJs(text).plugins.length >= 3);
});

test("install keeps a trailing comma when the game already had one", () => {
  const root = sandbox();
  const project = openProject(root);
  const before = fs.readFileSync(project.pluginsFile, "utf8");
  // Check out with CRLF (git's autocrlf on Windows) and the literal "\n];\n"
  // does not occur, so match the closing bracket through a regex instead.
  const withComma = before.replace(/\r?\n\];\r?\n?$/, ",\n];\n");
  assert.ok(withComma.endsWith(",\n];\n"), "the fixture should now end with a trailing comma");
  fs.writeFileSync(project.pluginsFile, withComma, "utf8");

  installPlugin(project);
  const text = fs.readFileSync(project.pluginsFile, "utf8");
  assert.ok(text.endsWith(",\n];\n"));
  assert.ok(parsePluginsJs(text).plugins.length >= 3);
});
