import { test, after } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

import {
  DEFAULT_LANGUAGE,
  TRANSLATION_FILE,
  installTranslation,
  isLanguageName,
  quoteRenpy,
  renderTranslationFile,
  translationPath,
  translationStatus,
  uninstallTranslation,
} from "../src/engines/renpy/runtime.js";

/**
 * Directories created by the tests, removed once the file has finished.
 *
 * @type {string[]}
 */
const created = [];

/** Build a throwaway project root with an empty game/ directory. */
function sandbox() {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "yakusha-renpy-runtime-"));
  created.push(root);
  const gameDir = path.join(root, "game");
  fs.mkdirSync(gameDir);
  fs.writeFileSync(path.join(gameDir, "script.rpy"), 'label start:\n    "Hello."\n    return\n', "utf8");
  return { root, gameDir };
}

/**
 * The project shape the runtime functions consume.
 *
 * @param {{ root: string, gameDir: string }} sandboxDir
 * @returns {{ root: string, gameDir: string, gameTitle: string }}
 */
function project(sandboxDir) {
  return { root: sandboxDir.root, gameDir: sandboxDir.gameDir, gameTitle: "Untitled Project" };
}

after(() => {
  for (const dir of created) fs.rmSync(dir, { recursive: true, force: true });
});

/**
 * Split rendered content into its comment header and its code body.
 *
 * @param {string} content rendered file
 * @returns {{ header: string[], body: string[] }}
 */
function sections(content) {
  const lines = content.split("\n");
  const header = [];
  let index = 0;
  while (index < lines.length && lines[index].startsWith("#")) {
    header.push(lines[index]);
    index += 1;
  }
  return { header, body: lines.slice(index) };
}

test("translationPath puts the file directly inside game/", () => {
  const dir = sandbox();
  assert.equal(translationPath(project(dir)), path.join(dir.gameDir, TRANSLATION_FILE));
  assert.equal(path.dirname(translationPath(project(dir))), dir.gameDir);
  assert.equal(TRANSLATION_FILE, "yakusha_translation.rpy");
  assert.equal(DEFAULT_LANGUAGE, "schinese");
});

test("translationPath rejects a project without a game directory", () => {
  assert.throws(() => translationPath({ root: "x" }), (error) => error.code === "E_USAGE");
  assert.throws(() => translationPath({ root: "x", gameDir: "" }), (error) => error.code === "E_USAGE");
});

test("isLanguageName accepts identifiers and rejects everything else", () => {
  for (const name of ["schinese", "french", "japanese_2", "_private", "A"]) {
    assert.equal(isLanguageName(name), true, name);
  }
  for (const name of ["", "2chinese", "chi nese", "chi-nese", "chi.nese", "None", "True", "False", null, 7, {}]) {
    assert.equal(isLanguageName(name), false, String(name));
  }
  // Case matters: python-none is a normal name, None is a constant.
  assert.equal(isLanguageName("none"), true);
});

test("quoteRenpy doubles backslashes", () => {
  assert.equal(quoteRenpy("a\\b"), "a\\\\b");
  assert.equal(quoteRenpy("\\\\"), "\\\\\\\\");
  // A backslash before n is two characters, not a newline.
  assert.equal(quoteRenpy("\\n"), "\\\\n");
});

test("quoteRenpy escapes double quotes", () => {
  assert.equal(quoteRenpy('say "hi"'), 'say \\"hi\\"');
  assert.equal(quoteRenpy('"'), '\\"');
});

test("quoteRenpy spells the control characters python spells", () => {
  assert.equal(quoteRenpy("a\nb"), "a\\nb");
  assert.equal(quoteRenpy("a\rb"), "a\\rb");
  assert.equal(quoteRenpy("a\tb"), "a\\tb");
  assert.equal(quoteRenpy("a\u000bb"), "a\\vb");
  assert.equal(quoteRenpy("a\u000cb"), "a\\fb");
  assert.equal(quoteRenpy("a\u0008b"), "a\\bb");
  assert.equal(quoteRenpy("a\u0007b"), "a\\ab");
});

test("quoteRenpy leaves ordinary text, tags and interpolations alone", () => {
  for (const text of ["你好，世界", "{b}bold{/b}", "[player] said", "50%", "a b c", "\\"]) {
    assert.equal(quoteRenpy(text), text === "\\" ? "\\\\" : text);
  }
  assert.equal(quoteRenpy(""), "");
});

test("renderTranslationFile starts with a header that names yakusha and no game", () => {
  const dir = sandbox();
  const content = renderTranslationFile([["Hello.", "你好。"]], { pluginVersion: "0.11.0" });
  const { header } = sections(content);
  assert.ok(header.length >= 2, "expected a comment header");
  assert.ok(header[0].startsWith("# Generated by yakusha 0.11.0"), header[0]);
  const text = header.join("\n");
  assert.match(text, /yakusha/);
  assert.match(text, /delete/i);
  // No machine path, no game name, no project title ever reaches the header.
  assert.ok(!text.includes(dir.root), "header leaked a temporary path");
  assert.ok(!text.includes(dir.gameDir), "header leaked a game path");
  assert.ok(!text.includes("Untitled Project"), "header leaked a project title");
  assert.ok(!/[A-Za-z]:[\\/]/.test(text), "header looks like it holds an absolute path");
});

test("renderTranslationFile guards the language on config.default_language", () => {
  const { body } = sections(renderTranslationFile([["Hello.", "你好。"]], { language: "schinese" }));
  assert.deepEqual(body.slice(0, 6), [
    "",
    "init python:",
    "    if config.default_language is None:",
    '        config.default_language = "schinese"',
    "",
    "translate schinese strings:",
  ]);
  const text = body.join("\n");
  assert.ok(text.indexOf("config.default_language is None") < text.indexOf("config.default_language ="));
  assert.ok(text.includes('translate schinese strings:'));
});

test("renderTranslationFile defaults the language and honours an explicit one", () => {
  assert.ok(renderTranslationFile([["a", "b"]]).includes('translate schinese strings:'));
  assert.ok(renderTranslationFile([["a", "b"]], { language: "french" }).includes("translate french strings:"));
  assert.ok(renderTranslationFile([["a", "b"]], { language: "french" }).includes('config.default_language = "french"'));
});

test("renderTranslationFile writes one old/new block per pair, separated by one blank line", () => {
  const content = renderTranslationFile([["Beta", "B"], ["Alpha", "A"]]);
  const { body } = sections(content);
  const tail = body.slice(body.indexOf("translate schinese strings:") + 1);
  assert.deepEqual(tail, [
    "",
    '    old "Alpha"',
    '    new "A"',
    "",
    '    old "Beta"',
    '    new "B"',
    "",
  ]);
});

test("renderTranslationFile sorts by source text so caller order cannot matter", () => {
  const forward = renderTranslationFile([["a", "1"], ["b", "2"], ["c", "3"]]);
  const shuffled = renderTranslationFile([["c", "3"], ["a", "1"], ["b", "2"]]);
  const reversed = renderTranslationFile([["c", "3"], ["b", "2"], ["a", "1"]]);
  assert.equal(forward, shuffled);
  assert.equal(forward, reversed);
  assert.ok(forward.indexOf('old "a"') < forward.indexOf('old "b"'));
  assert.ok(forward.indexOf('old "b"') < forward.indexOf('old "c"'));
});

test("renderTranslationFile keeps the first value for a duplicated source", () => {
  const content = renderTranslationFile([
    ["Word", "first"],
    ["Other", "x"],
    ["Word", "second"],
  ]);
  const hits = content.split("\n").filter((line) => line.includes('old "Word"'));
  assert.equal(hits.length, 1, "duplicate old must be removed");
  assert.ok(content.includes('    new "first"'));
  assert.ok(!content.includes('"second"'));
});

test("renderTranslationFile skips empty and malformed pairs", () => {
  const content = renderTranslationFile([
    ["", "empty source"],
    ["empty target", ""],
    ["   ", "blank source"],
    ["blank target", "  "],
    [null, "x"],
    ["y", null],
    ["kept", "ok"],
    [],
    {},
  ]);
  const olds = content.split("\n").filter((line) => line.trimStart().startsWith("old "));
  assert.equal(olds.length, 1);
  assert.equal(olds[0], '    old "kept"');
});

test("renderTranslationFile accepts { source, target } objects", () => {
  const fromObjects = renderTranslationFile([{ source: "a", target: "1" }, { source: "b", target: "2" }]);
  const fromArrays = renderTranslationFile([["a", "1"], ["b", "2"]]);
  assert.equal(fromObjects, fromArrays);
});

test("renderTranslationFile escapes both sides of a pair", () => {
  const content = renderTranslationFile([['He said "hi"', '他说"你好"']]);
  assert.ok(content.includes('    old "He said \\"hi\\""'));
  assert.ok(content.includes('    new "他说\\"你好\\""'));
});

test("renderTranslationFile uses LF and exactly one trailing newline", () => {
  const content = renderTranslationFile([["a", "b"]]);
  assert.ok(!content.includes("\r"));
  assert.ok(content.endsWith("\n"));
  assert.ok(!content.endsWith("\n\n"));
});

test("renderTranslationFile is byte stable for the same input", () => {
  const pairs = [["b", "2"], ["a", "1"], ["a", "override"], ["c", "3"]];
  const first = renderTranslationFile(pairs, { language: "schinese", pluginVersion: "0.11.0" });
  const second = renderTranslationFile(pairs, { language: "schinese", pluginVersion: "0.11.0" });
  assert.equal(first, second);
  const copy = pairs.map((pair) => [...pair]);
  assert.equal(renderTranslationFile(copy, { language: "schinese", pluginVersion: "0.11.0" }), first);
});

test("renderTranslationFile rejects an unusable language name", () => {
  for (const language of ["", "chi nese", "2x", "None", null, 7]) {
    assert.throws(
      () => renderTranslationFile([["a", "b"]], { language }),
      (error) => error.code === "E_USAGE" && /language name/.test(error.message),
      String(language),
    );
  }
});

test("renderTranslationFile rejects a non-array pair list", () => {
  assert.throws(() => renderTranslationFile(null), (error) => error.code === "E_USAGE");
  assert.throws(() => renderTranslationFile("a"), (error) => error.code === "E_USAGE");
});

test("renderTranslationFile emits a code-free file when nothing survives", () => {
  const content = renderTranslationFile([]);
  assert.ok(content.startsWith("#"));
  assert.ok(!content.includes("init python:"));
  // The header mentions the mechanism in prose; no block may be emitted.
  assert.ok(!/^translate /m.test(content));
  assert.ok(content.endsWith("\n"));
});

test("installTranslation creates the file on the first run", () => {
  const dir = sandbox();
  const result = installTranslation(project(dir), [["Hello.", "你好。"]]);
  assert.deepEqual(result, {
    path: path.join(dir.gameDir, TRANSLATION_FILE),
    language: "schinese",
    entries: 1,
    created: true,
    changed: true,
  });
  assert.equal(fs.readFileSync(result.path, "utf8"), renderTranslationFile([["Hello.", "你好。"]]));
  // The atomic write left no temp file behind.
  assert.deepEqual(fs.readdirSync(dir.gameDir).sort(), ["script.rpy", TRANSLATION_FILE]);
});

test("installTranslation leaves an identical file untouched", () => {
  const dir = sandbox();
  const first = installTranslation(project(dir), [["Hello.", "你好。"]]);
  const before = fs.statSync(first.path).mtimeMs;
  const second = installTranslation(project(dir), [["Hello.", "你好。"]]);
  assert.equal(second.created, false);
  assert.equal(second.changed, false);
  assert.equal(second.entries, 1);
  assert.equal(fs.statSync(first.path).mtimeMs, before);
});

test("installTranslation rewrites a different file", () => {
  const dir = sandbox();
  installTranslation(project(dir), [["Hello.", "你好。"]]);
  const result = installTranslation(project(dir), [["Hello.", "你好。"], ["Bye.", "再见。"]]);
  assert.equal(result.created, false);
  assert.equal(result.changed, true);
  assert.equal(result.entries, 2);
  assert.ok(fs.readFileSync(result.path, "utf8").includes('old "Bye."'));
});

test("installTranslation records a language change and reports it back", () => {
  const dir = sandbox();
  installTranslation(project(dir), [["a", "1"]], { language: "schinese" });
  const result = installTranslation(project(dir), [["a", "1"]], { language: "french" });
  assert.equal(result.language, "french");
  assert.equal(result.changed, true);
  assert.equal(translationStatus(project(dir)).language, "french");
});

test("installTranslation refuses an invalid language before touching the disk", () => {
  const dir = sandbox();
  assert.throws(
    () => installTranslation(project(dir), [["a", "b"]], { language: "bad lang" }),
    (error) => error.code === "E_USAGE",
  );
  assert.equal(fs.existsSync(path.join(dir.gameDir, TRANSLATION_FILE)), false);
});

test("installTranslation refuses a target outside the project root", () => {
  const dir = sandbox();
  const outside = fs.mkdtempSync(path.join(os.tmpdir(), "yakusha-renpy-outside-"));
  created.push(outside);
  const escaped = { root: dir.root, gameDir: outside };
  const target = path.join(outside, TRANSLATION_FILE);
  assert.throws(
    () => installTranslation(escaped, [["a", "b"]]),
    (error) => error.code === "E_IO" && error.message === "refusing to write outside the project root: " + target,
  );
  assert.equal(fs.existsSync(target), false);
  assert.throws(() => uninstallTranslation(escaped), (error) => error.code === "E_IO");
});

test("uninstallTranslation removes the file and is idempotent", () => {
  const dir = sandbox();
  const target = path.join(dir.gameDir, TRANSLATION_FILE);
  const fresh = uninstallTranslation(project(dir));
  assert.deepEqual(fresh, { path: target, removed: false });

  installTranslation(project(dir), [["a", "b"]]);
  assert.deepEqual(uninstallTranslation(project(dir)), { path: target, removed: true });
  assert.equal(fs.existsSync(target), false);
  assert.deepEqual(fs.readdirSync(dir.gameDir), ["script.rpy"]);
  assert.deepEqual(uninstallTranslation(project(dir)), { path: target, removed: false });
});

test("uninstallTranslation restores the game to its original bytes", () => {
  const dir = sandbox();
  const script = path.join(dir.gameDir, "script.rpy");
  const original = fs.readFileSync(script);
  installTranslation(project(dir), [['"Hello."', "你好。"]]);
  uninstallTranslation(project(dir));
  assert.deepEqual(fs.readFileSync(script), original);
  assert.deepEqual(fs.readdirSync(dir.gameDir), ["script.rpy"]);
});

test("translationStatus describes an absent file", () => {
  const dir = sandbox();
  const status = translationStatus(project(dir));
  assert.deepEqual(status, {
    path: path.join(dir.gameDir, TRANSLATION_FILE),
    exists: false,
    language: "schinese",
    entries: 0,
  });
});

test("translationStatus counts the installed entries and reads the language back", () => {
  const dir = sandbox();
  installTranslation(project(dir), [["a", "1"], ["b", "2"], ["c", "3"]], { language: "japanese" });
  const status = translationStatus(project(dir));
  assert.equal(status.exists, true);
  assert.equal(status.language, "japanese");
  assert.equal(status.entries, 3);
  assert.equal(status.path, path.join(dir.gameDir, TRANSLATION_FILE));
});

test("translationStatus reports zero entries for an existing but unreadable file", () => {
  const dir = sandbox();
  // A directory in the file's place is the portable way to make the read fail.
  fs.mkdirSync(path.join(dir.gameDir, TRANSLATION_FILE));
  const status = translationStatus(project(dir));
  assert.equal(status.exists, true);
  assert.equal(status.entries, 0);
  assert.equal(status.language, "schinese");
});

test("translationStatus prefers an explicitly requested language over the default", () => {
  const dir = sandbox();
  assert.equal(translationStatus(project(dir), { language: "korean" }).language, "korean");
  assert.equal(translationStatus(project(dir), { language: "not a name" }).language, "schinese");
});
