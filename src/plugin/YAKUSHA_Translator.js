/*:
 * @target MZ
 * @plugindesc Runtime translation driven by a yakusha dictionary.
 * @author MagicalAlmond
 * @url https://github.com/MagicalAlmond/Yakusha
 *
 * @param dictionaryPath
 * @text Dictionary path
 * @desc Dictionary file, relative to the game folder.
 * @default yakusha/dictionary.json
 *
 * @param strictCodes
 * @text Strict escape codes
 * @desc Drop a translation whose escape codes differ from the source instead of rendering it.
 * @type boolean
 * @on ON
 * @off OFF
 * @default true
 *
 * @param debug
 * @text Debug logging
 * @desc Write translation problems to the developer console.
 * @type boolean
 * @on ON
 * @off OFF
 * @default false
 *
 * @help
 * YAKUSHA_Translator replaces player visible text in the game database and in every
 * event command as the data files are loaded. Nothing in the game is rewritten
 * on disk, so removing the plugin restores the original language.
 *
 * Generated by yakusha. The rules block below is kept in sync with
 * src/core/fields.js and is checked by test/rules-sync.test.js - edit that
 * module, not this file.
 */
(() => {
    "use strict";

    const PLUGIN_NAME = "YAKUSHA_Translator";
    const VERSION = "0.9.0";

    //<<<RULES>>>
    const RULES = {"dbFields":{"Actors.json":["name","nickname","profile"],"Classes.json":["name"],"Skills.json":["name","description","message1","message2"],"Items.json":["name","description"],"Weapons.json":["name","description"],"Armors.json":["name","description"],"Enemies.json":["name"],"States.json":["name","message1","message2","message3","message4"],"Tilesets.json":["name"],"CommonEvents.json":["name"],"MapInfos.json":["name"]},"systemFields":["gameTitle","currencyUnit","terms.basic[]","terms.commands[]","terms.params[]","terms.messages","armorTypes[]","elements[]","skillTypes[]","weaponTypes[]","equipTypes[]"],"commands":{"101":"4","102":"0[]","320":"1","324":"1","325":"1","401":"0","405":"0"}};
    //<<<END-RULES>>>
    //<<<EMBEDDED>>>
    const EMBEDDED = null;
    //<<<END-EMBEDDED>>>

    const BS = String.fromCharCode(92);
    const IDEOGRAPHIC_SPACE = String.fromCharCode(0x3000);
    const SINGLE_CODES = new Set(["$", ".", "|", "^", "!", ">", "<", "{", "}", BS]);
    const MAP_FILE = /^Map[0-9]+[.]json$/i;
    const COMMAND_ONLY = new Set(["CommonEvents.json", "Troops.json"]);

    const params =
        typeof PluginManager !== "undefined" && typeof PluginManager.parameters === "function"
            ? PluginManager.parameters(PLUGIN_NAME) || {}
            : {};
    const DICT_PATH = String(params.dictionaryPath || "yakusha/dictionary.json");
    const STRICT = String(params.strictCodes === undefined ? "true" : params.strictCodes) !== "false";
    const DEBUG = String(params.debug || "false") === "true";

    const state = {
        dict: Object.create(null),
        norm: null,
        loaded: false,
        source: null,
        translated: 0,
        lookups: 0,
        misses: 0,
        rejected: 0,
        documents: 0,
        hookInstalled: false,
    };

    function warn(message) {
        if (typeof console !== "undefined" && console.warn) console.warn("[yakusha] " + message);
    }

    function debug(message) {
        if (DEBUG) warn(message);
    }

    // ------------------------------------------------------------------
    // Escape code aware tokenising, mirrors src/core/textkey.js
    // ------------------------------------------------------------------

    function tokenize(text) {
        const out = [];
        let buf = "";
        let i = 0;
        while (i < text.length) {
            const ch = text[i];
            if (ch !== BS) {
                buf += ch;
                i += 1;
                continue;
            }
            const next = text[i + 1];
            if (next === undefined) {
                buf += ch;
                i += 1;
                continue;
            }
            let token = null;
            if (next === BS) {
                token = BS + BS;
            } else if (SINGLE_CODES.has(next)) {
                token = BS + next;
            } else if (/[A-Za-z]/.test(next)) {
                let j = i + 1;
                while (j < text.length && /[A-Za-z]/.test(text[j])) j += 1;
                if (text[j] === "[") {
                    let k = j + 1;
                    while (k < text.length && /[0-9]/.test(text[k])) k += 1;
                    if (text[k] === "]" && k > j + 1) token = text.slice(i, k + 1);
                }
                if (token === null) token = text.slice(i, j);
            }
            if (token === null) {
                buf += next;
                i += 2;
                continue;
            }
            if (buf) {
                out.push({ t: "text", v: buf });
                buf = "";
            }
            out.push({ t: "code", v: token });
            i += token.length;
        }
        if (buf) out.push({ t: "text", v: buf });
        return out;
    }

    function controlCodes(text) {
        if (typeof text !== "string" || text.indexOf(BS) < 0) return [];
        const out = [];
        for (const token of tokenize(text)) if (token.t === "code") out.push(token.v);
        return out;
    }

    function sameCodes(a, b) {
        const x = controlCodes(a);
        const y = controlCodes(b);
        if (x.length !== y.length) return false;
        for (let i = 0; i < x.length; i += 1) if (x[i] !== y[i]) return false;
        return true;
    }

    function normalizeKey(text) {
        return text.normalize("NFKC").split(IDEOGRAPHIC_SPACE).join(" ").replace(/ +/g, " ").trim();
    }

    // ------------------------------------------------------------------
    // Dictionary
    // ------------------------------------------------------------------

    function fileUrlToPath(url) {
        const text = String(url || "").replace(/[?#].*$/, "");
        if (text.slice(0, 7).toLowerCase() !== "file://") return null;
        let rest = text.slice(7);
        try {
            rest = decodeURIComponent(rest);
        } catch (error) {
            /* keep the raw form */
        }
        if (rest.charAt(0) === "/" && rest.charAt(2) === ":") rest = rest.slice(1);
        return rest;
    }

    function safeRequire(name) {
        try {
            if (typeof require === "function") return require(name);
        } catch (error) {
            /* browser context */
        }
        return null;
    }

    function candidateDirs(nodePath) {
        const dirs = [];
        try {
            const asPath = fileUrlToPath(typeof window !== "undefined" ? window.location.href : "");
            if (asPath) dirs.push(nodePath.dirname(asPath));
        } catch (error) {
            /* ignore */
        }
        try {
            if (typeof process !== "undefined" && typeof process.cwd === "function") dirs.push(process.cwd());
        } catch (error) {
            /* ignore */
        }
        dirs.push(".");
        return dirs;
    }

    function readDictionarySource() {
        if (EMBEDDED && typeof EMBEDDED === "object") {
            return { text: JSON.stringify(EMBEDDED), source: "embedded" };
        }
        const fs = safeRequire("fs");
        const nodePath = safeRequire("path");
        if (fs && nodePath && typeof fs.readFileSync === "function") {
            for (const dir of candidateDirs(nodePath)) {
                let file;
                try {
                    file = nodePath.join(dir, ...DICT_PATH.split("/"));
                } catch (error) {
                    continue;
                }
                try {
                    if (fs.existsSync(file)) return { text: fs.readFileSync(file, "utf8"), source: file };
                } catch (error) {
                    /* try the next candidate */
                }
            }
        }
        if (typeof XMLHttpRequest !== "undefined") {
            try {
                const xhr = new XMLHttpRequest();
                xhr.open("GET", DICT_PATH, false);
                if (typeof xhr.overrideMimeType === "function") xhr.overrideMimeType("application/json");
                xhr.send();
                if (xhr.status < 400 && xhr.responseText) {
                    return { text: xhr.responseText, source: DICT_PATH };
                }
            } catch (error) {
                /* no dictionary reachable */
            }
        }
        return null;
    }

    function loadDictionary() {
        const raw = readDictionarySource();
        if (!raw) {
            state.loaded = false;
            return 0;
        }
        let parsed;
        try {
            parsed = JSON.parse(raw.text);
        } catch (error) {
            warn("dictionary is not valid JSON: " + raw.source);
            state.loaded = false;
            return 0;
        }
        const entries = parsed && typeof parsed === "object" && parsed.entries ? parsed.entries : parsed;
        const dict = Object.create(null);
        let count = 0;
        if (entries && typeof entries === "object") {
            for (const key of Object.keys(entries)) {
                const value = entries[key];
                const text = typeof value === "string" ? value : value && typeof value.text === "string" ? value.text : "";
                if (text) {
                    dict[key] = text;
                    count += 1;
                }
            }
        }
        state.dict = dict;
        state.norm = null;
        state.loaded = true;
        state.source = raw.source;
        debug(count + " entries loaded from " + raw.source);
        return count;
    }

    function buildNormIndex() {
        state.norm = Object.create(null);
        for (const key of Object.keys(state.dict)) {
            const normalised = normalizeKey(key);
            if (state.norm[normalised] === undefined) state.norm[normalised] = state.dict[key];
        }
    }

    // ------------------------------------------------------------------
    // Lookup
    // ------------------------------------------------------------------

    function translateString(source) {
        if (typeof source !== "string" || source.length === 0) return source;
        state.lookups += 1;
        let target = state.dict[source];
        if (target === undefined) {
            if (!state.norm) buildNormIndex();
            target = state.norm[normalizeKey(source)];
        }
        if (target === undefined || target === "") {
            state.misses += 1;
            return source;
        }
        if (STRICT && !sameCodes(source, target)) {
            state.rejected += 1;
            debug("escape codes differ from source: " + source.slice(0, 40));
            return source;
        }
        state.translated += 1;
        return target;
    }

    // ------------------------------------------------------------------
    // Structural walkers
    // ------------------------------------------------------------------

    function resolveChain(root, parts) {
        let nodes = [root];
        for (const part of parts) {
            const isArray = part.endsWith("[]");
            const key = isArray ? part.slice(0, -2) : part;
            const next = [];
            for (const node of nodes) {
                if (!node || typeof node !== "object") continue;
                const value = node[key];
                if (isArray) {
                    if (Array.isArray(value)) for (const item of value) next.push(item);
                } else if (value !== undefined && value !== null) {
                    next.push(value);
                }
            }
            nodes = next;
        }
        return nodes;
    }

    function translateLeaf(node) {
        if (Array.isArray(node)) {
            for (let i = 0; i < node.length; i += 1) {
                if (typeof node[i] === "string") node[i] = translateString(node[i]);
            }
            return;
        }
        if (node && typeof node === "object") {
            for (const key of Object.keys(node)) {
                if (typeof node[key] === "string") node[key] = translateString(node[key]);
            }
        }
    }

    function translatePath(root, dotted) {
        const parts = dotted.split(".");
        const last = parts.pop();
        const isArray = last.endsWith("[]");
        const key = isArray ? last.slice(0, -2) : last;
        const parents = parts.length === 0 ? [root] : resolveChain(root, parts);
        for (const parent of parents) {
            if (!parent || typeof parent !== "object") continue;
            const value = parent[key];
            if (isArray) {
                if (Array.isArray(value)) translateLeaf(value);
            } else if (typeof value === "string") {
                parent[key] = translateString(value);
            } else if (value && typeof value === "object") {
                translateLeaf(value);
            }
        }
    }

    function walkCommands(node, visit) {
        if (Array.isArray(node)) {
            for (const item of node) walkCommands(item, visit);
            return;
        }
        if (node === null || typeof node !== "object") return;
        if (typeof node.code === "number") {
            const parameters = Array.isArray(node.parameters) ? node.parameters : null;
            if (parameters) visit(node.code, parameters);
            return;
        }
        for (const key of Object.keys(node)) walkCommands(node[key], visit);
    }

    function translateParams(parameters, spec) {
        if (spec.endsWith("[]")) {
            const value = parameters[Number(spec.slice(0, -2))];
            if (!Array.isArray(value)) return;
            for (let i = 0; i < value.length; i += 1) {
                if (typeof value[i] === "string") value[i] = translateString(value[i]);
            }
            return;
        }
        const index = Number(spec);
        if (typeof parameters[index] === "string") parameters[index] = translateString(parameters[index]);
    }

    function translateCommands(root) {
        walkCommands(root, (code, parameters) => {
            const spec = RULES.commands[String(code)];
            if (spec) translateParams(parameters, spec);
        });
    }

    function stripTestPrefix(fileName) {
        return fileName.slice(0, 5) === "Test_" ? fileName.slice(5) : fileName;
    }

    function translateDocument(fileName, data) {
        if (!data || typeof data !== "object") return;
        const base = stripTestPrefix(String(fileName || ""));
        state.documents += 1;
        const fields = RULES.dbFields[base];
        if (fields && Array.isArray(data)) {
            for (const record of data) {
                if (!record || typeof record !== "object") continue;
                for (const field of fields) {
                    if (typeof record[field] === "string") record[field] = translateString(record[field]);
                }
            }
            // CommonEvents.json is both a database (each entry has a name) and a
            // command list, so it must not stop here.
            if (COMMAND_ONLY.has(base)) translateCommands(data);
            return;
        }
        if (base === "System.json") {
            for (const field of RULES.systemFields) translatePath(data, field);
            return;
        }
        if (base === "MapInfos.json") {
            if (Array.isArray(data)) {
                for (const info of data) {
                    if (info && typeof info.name === "string") info.name = translateString(info.name);
                }
            }
            return;
        }
        if (MAP_FILE.test(base)) {
            if (typeof data.displayName === "string") data.displayName = translateString(data.displayName);
            translateCommands(data);
            return;
        }
        if (COMMAND_ONLY.has(base)) translateCommands(data);
    }

    // ------------------------------------------------------------------
    // Engine hook
    // ------------------------------------------------------------------

    /**
     * MV parses and assigns inside loadDataFile's own XHR callback, so there is
     * no onXhrLoad to wrap. Instead record (name, src) pairs on the way in and
     * match the finished object by identity on the way out.
     */
    function installMvHook() {
        if (
            typeof DataManager.onLoad !== "function" ||
            typeof DataManager.loadDataFile !== "function"
        ) {
            debug("DataManager.onLoad/loadDataFile are unavailable, nothing to hook");
            return false;
        }
        const pending = [];
        const originalLoadDataFile = DataManager.loadDataFile;
        DataManager.loadDataFile = function (name, src) {
            pending.push({ name: name, src: src });
            if (pending.length > 64) pending.splice(0, pending.length - 64);
            return originalLoadDataFile.apply(this, arguments);
        };
        const originalOnLoad = DataManager.onLoad;
        DataManager.onLoad = function (object) {
            originalOnLoad.call(this, object);
            try {
                if (!object || typeof window === "undefined") return;
                for (let i = pending.length - 1; i >= 0; i -= 1) {
                    const entry = pending[i];
                    if (window[entry.name] === object) {
                        pending.splice(i, 1);
                        translateDocument(entry.src, object);
                        return;
                    }
                }
            } catch (error) {
                warn("could not translate a data file: " + (error && error.message ? error.message : error));
            }
        };
        state.hookInstalled = true;
        return true;
    }

    function installDataHook() {
        if (typeof DataManager === "undefined") {
            debug("DataManager is unavailable, nothing to hook");
            return false;
        }
        if (typeof DataManager.onXhrLoad !== "function") return installMvHook();
        const original = DataManager.onXhrLoad;
        DataManager.onXhrLoad = function (xhr, name, src, url) {
            original.call(this, xhr, name, src, url);
            try {
                const data = typeof window !== "undefined" ? window[name] : undefined;
                if (!data) return;
                translateDocument(src, data);
            } catch (error) {
                warn("could not translate " + src + ": " + (error && error.message ? error.message : error));
            }
        };
        state.hookInstalled = true;
        return true;
    }

    function stats() {
        return {
            version: VERSION,
            dictionary: state.source,
            loaded: state.loaded,
            entries: Object.keys(state.dict).length,
            documents: state.documents,
            lookups: state.lookups,
            translated: state.translated,
            misses: state.misses,
            rejected: state.rejected,
            hookInstalled: state.hookInstalled,
        };
    }

    loadDictionary();
    installDataHook();

    if (typeof window !== "undefined") {
        window.__YAKUSHA = {
            version: VERSION,
            rules: RULES,
            stats: stats,
            translate: translateString,
            translateDocument: translateDocument,
            reload: () => {
                const count = loadDictionary();
                warn("reloaded " + count + " entries");
                return count;
            },
        };
    }
    debug("ready, " + Object.keys(state.dict).length + " entries");
})();
